const KEY = 'crous.lang';

/** The language picked in the app, else the first supported one in the device's preference list, else English. */
function initialLang(): string {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && saved in strings) return saved;
  } catch {} // storage blocked: fall back to the device languages
  for (const { languageCode } of getLocales()) {
    const code = languageCode === 'zh' ? 'zh-Hant' : languageCode; // only Traditional Chinese is offered
    if (code && code in strings) return code;
  }
  return 'en';
}

// `let` exports are live bindings: after setLang, every importer reads the new values on its next render.
export let lang = initialLang();
export let t = strings[lang];
markPageLang();

// Web: screen readers and the browser's translate offer go by <html lang>.
function markPageLang() {
  if (Platform.OS === 'web') document.documentElement.lang = lang;
}

export function setLang(code: string) {
  lang = code;
  t = strings[code];
  markPageLang();
  try {
    localStorage.setItem(KEY, code);
  } catch {}
}
